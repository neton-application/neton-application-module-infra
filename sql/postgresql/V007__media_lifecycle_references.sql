-- ─────────────────────────────────────────────────────────────
-- 媒体生命周期与引用登记（infra-media §6，M1）
-- ─────────────────────────────────────────────────────────────

-- 生命周期：temporary → attached → orphaned → deleted。
-- 历史行与未声明 managedLifecycle 的业务类型恒为 attached，永远不进清理。
ALTER TABLE infra_files ADD COLUMN IF NOT EXISTS lifecycle VARCHAR(16) NOT NULL DEFAULT 'attached';
ALTER TABLE infra_files ADD COLUMN IF NOT EXISTS lifecycle_at BIGINT;
ALTER TABLE infra_files ADD COLUMN IF NOT EXISTS purged_at BIGINT;

UPDATE infra_files SET lifecycle_at = created_at WHERE lifecycle_at IS NULL;

ALTER TABLE infra_files ADD CONSTRAINT ck_infra_files_lifecycle
    CHECK (lifecycle IN ('temporary', 'attached', 'orphaned', 'deleted'));

-- 清理任务的扫描路径：只看非 attached 的行，部分索引保持很小。
CREATE INDEX IF NOT EXISTS idx_infra_files_lifecycle
    ON infra_files(lifecycle, lifecycle_at) WHERE lifecycle <> 'attached';
-- 清理删物理对象前确认同路径没有存活记录（内容寻址多行共用对象）。
CREATE INDEX IF NOT EXISTS idx_infra_files_path ON infra_files(path);

COMMENT ON COLUMN infra_files.lifecycle IS '媒体生命周期：temporary/attached/orphaned/deleted';
COMMENT ON COLUMN infra_files.lifecycle_at IS '生命周期最近变化时刻（epoch ms），宽限期起点';
COMMENT ON COLUMN infra_files.purged_at IS '物理对象清理完成时刻（epoch ms）；deleted 且为空表示待清理';

-- 引用登记：一行一个（文件, 引用对象, 用途）。删除对象只解除自己的引用。
CREATE TABLE IF NOT EXISTS infra_media_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id VARCHAR(64) NOT NULL,
    owner_type VARCHAR(64) NOT NULL,
    owner_id VARCHAR(128) NOT NULL,
    usage VARCHAR(64) NOT NULL,
    created_at BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_infra_media_references UNIQUE (file_id, owner_type, owner_id, usage)
);

CREATE INDEX IF NOT EXISTS idx_infra_media_references_owner
    ON infra_media_references(owner_type, owner_id);

COMMENT ON TABLE infra_media_references IS '媒体引用登记（infra-media §6.2）';
COMMENT ON COLUMN infra_media_references.file_id IS '对外文件 ID（infra_files.file_id）';
COMMENT ON COLUMN infra_media_references.owner_type IS '引用对象类型，如 content.item';
COMMENT ON COLUMN infra_media_references.owner_id IS '引用对象 ID';
COMMENT ON COLUMN infra_media_references.usage IS '用途，须在文件业务类型声明的 usages 内';
COMMENT ON COLUMN infra_media_references.created_at IS '登记时间（epoch ms）';
